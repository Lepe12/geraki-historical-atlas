import assert from "node:assert/strict";
import { parse, afterWake, matchPlace } from "./assistant-intents.js";
assert.equal(parse("Άνοιξε").type, "open");
assert.equal(parse("εμφανίσου").type, "open");
assert.equal(parse("Κλείσε").type, "close");
assert.deepEqual(parse("γύρνα δεξιά"), { type: "turn", dir: 1 });
assert.deepEqual(parse("Γύρνα αριστερά."), { type: "turn", dir: -1 });
assert.deepEqual(parse("ψάξε Λάντζας Μήλος"), { type: "search", query: "Λάντζας Μήλος" });
assert.equal(parse("δείξε μου τον Λάντζα").type, "lantzas");
assert.deepEqual(parse("δείξε μου την Κέρκυρα"), { type: "place", place: "κερκυρα" });
assert.deepEqual(parse("τρισδιάστατο"), { type: "map3d", on: true });
assert.deepEqual(parse("δισδιάστατο"), { type: "map3d", on: false });
assert.equal(parse("πόσο κάνει ένας καφές").type, "unknown");
assert.equal(afterWake("Ναμπού, άνοιξε"), "ανοιξε");
assert.equal(afterWake("Ναμπού"), "");
assert.equal(afterWake("καλημέρα"), null);
const places = [{ id: "c", names: ["Corfù", "Κέρκυρα"] }, { id: "h", names: ["Candia", "Χάνδακας"] }, { id: "v", names: ["Βενετία"] }, { id: "o", names: ["Οθωμανική αυτοκρατορία"] }];
assert.equal(matchPlace("κερκυρα", places).id, "c");
assert.equal(matchPlace("Χάνδακα", places).id, "h");
assert.equal(matchPlace("βενετια", places).id, "v");
assert.equal(matchPlace("οθωμανικη αυτοκρατορια", places).id, "o");
assert.equal(matchPlace("ιαπωνια", places), null);
console.log("assistant intents ok");
